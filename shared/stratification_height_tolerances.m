function tolerances = stratification_height_tolerances()
%STRATIFICATION_HEIGHT_TOLERANCES Dimensionless thresholds from Table 2.4.
%   Epsilon is the central greyscale threshold. EpsilonLower and EpsilonUpper
%   define the sensitivity range, applied at each sampled time. NaN means no
%   range was listed. These values are not dimensional density differences.

    configuration = { ...
        'Rectangular, H = 0.300 m'; ...
        'Rectangular, H = 0.300 m'; ...
        'Rectangular, H = 0.300 m'; ...
        'Rectangular, H = 0.300 m'; ...
        'Rectangular, H = 0.300 m'; ...
        'Rectangular, H_r = 0.150 m'; ...
        'Rectangular, H_r = 0.150 m'; ...
        'Two-source, H_r = 0.150 m'; ...
        'Two-source, H_r = 0.150 m'; ...
        'Two-source, H_r = 0.150 m'; ...
        'Circular'; ...
        'Circular'};
    flow_cm3_min = [10; 20; 30; 40; 70; 30; 70; 20; 40; 80; 20; 50];
    epsilon = [0.050; 0.090; 0.040; 0.080; 0.065; 0.075; ...
        0.085; 0.065; 0.080; 0.115; 0.085; 0.0775];
    lower = [NaN; NaN; 0.010; 0.030; 0.020; 0.045; ...
        0.040; 0.025; NaN; 0.035; 0.020; 0.050];
    upper = [NaN; NaN; 0.070; 0.130; 0.110; 0.105; ...
        0.130; 0.105; NaN; 0.195; 0.150; 0.105];
    tolerances = table(configuration, flow_cm3_min, epsilon, lower, upper, ...
        'VariableNames', {'Configuration', 'Flow_cm3_min', ...
        'Epsilon', 'EpsilonLower', 'EpsilonUpper'});
end
